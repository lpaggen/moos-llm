#!/usr/bin/env python3
"""Build provenance-checked SFT data from exact runtime-prompt teacher audits."""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
from collections import Counter
from pathlib import Path
from typing import Any

from agents.agent_oow import BASE_SYSTEM_PROMPT
from sft.prepare_oow_sft import split_by_episode, write_jsonl
from tools.build_teacher_dataset import audit_quality
from tools.extract_oow_pairs import extract_pairs


ALLOWED_ACTIONS = {
    "skip",
    "maintain_course",
    "alter_course",
    "set_speed",
    "stop",
    "resume",
    "rejoin_route",
}
EXPECTED_USER_FIELDS = {"allowed_actions", "briefing"}
OPTIONAL_USER_FIELDS = {"active_action_review"}
FORBIDDEN_TARGET_TERMS = (
    "deterministic_colregs_oracle",
    "the oracle",
    "oracle classifies",
    "the classifier",
    "classifier classifies",
    "authoritative classification",
)
VALID_RULES = {2, 5, 6, 7, 8, 13, 14, 15, 16, 17, 18, 19, 34}
RULE_CITATION = re.compile(r"\bRules?\s+([0-9][0-9,\sand\-–]*)", re.IGNORECASE)


def read_campaign_audits(inputs: list[Path]) -> list[Path]:
    paths: set[Path] = set()
    for item in inputs:
        if not item.exists():
            raise FileNotFoundError(item)
        if item.is_dir():
            manifest = item / "campaign.json"
            if manifest.is_file():
                config = json.loads(manifest.read_text(encoding="utf-8"))
                if config.get("openai_prompt_profile") != "runtime-base":
                    raise ValueError(
                        f"{manifest}: campaign was not generated with runtime-base prompt"
                    )
            paths.update(item.glob("seed_*.jsonl"))
            paths.update(item.rglob("audit.jsonl"))
        else:
            paths.add(item)
    return sorted(path.resolve() for path in paths)


def canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def cited_rules(reason: str) -> set[int]:
    rules: set[int] = set()
    for match in RULE_CITATION.finditer(reason):
        rules.update(int(value) for value in re.findall(r"\d+", match.group(1)))
    return rules


def validate_decision(decision: dict[str, Any], allowed: list[str]) -> None:
    action = decision.get("action")
    if action not in ALLOWED_ACTIONS or action not in allowed:
        raise ValueError(f"invalid or unavailable action: {action!r}")
    reason = decision.get("reason")
    if not isinstance(reason, str) or not reason.strip():
        raise ValueError("decision reason is empty")
    lowered = reason.casefold()
    contaminated = [term for term in FORBIDDEN_TARGET_TERMS if term in lowered]
    if contaminated:
        raise ValueError("target references unavailable evidence: " + ", ".join(contaminated))
    invalid_rules = cited_rules(reason) - VALID_RULES
    if invalid_rules:
        raise ValueError(f"target cites invalid rules: {sorted(invalid_rules)}")
    degrees = decision.get("degrees")
    speed = decision.get("speed")
    if action == "alter_course":
        if not isinstance(degrees, (int, float)) or degrees == 0 or abs(degrees) > 60:
            raise ValueError(f"invalid alter_course degrees: {degrees!r}")
    elif degrees not in (0, 0.0, None):
        raise ValueError(f"unused degrees must be zero for {action}: {degrees!r}")
    if action == "set_speed":
        if not isinstance(speed, (int, float)) or speed <= 0:
            raise ValueError(f"invalid set_speed speed: {speed!r}")
    elif speed not in (0, 0.0, None):
        raise ValueError(f"unused speed must be zero for {action}: {speed!r}")


def validate_audit_provenance(path: Path) -> dict[str, Any]:
    startup = None
    with path.open(encoding="utf-8") as source:
        for line in source:
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                continue
            if row.get("event") == "startup":
                startup = row
                break
    if startup is None:
        raise ValueError(f"{path}: missing startup provenance")
    if startup.get("openai_api") is not True:
        raise ValueError(f"{path}: labels were not generated by the OpenAI teacher")
    if startup.get("openai_prompt_profile") != "runtime-base":
        raise ValueError(f"{path}: audit does not use the runtime-base teacher prompt")
    model = startup.get("oow_model")
    if not isinstance(model, str) or not model.strip():
        raise ValueError(f"{path}: missing teacher model identity")
    return startup


def episode_rows(path: Path) -> list[dict[str, Any]]:
    validate_audit_provenance(path)
    rows: list[dict[str, Any]] = []
    source_file = str(path)
    for cycle_id, pair in enumerate(
        extract_pairs(path, validated_only=True, chat_format=False), start=1
    ):
        source = pair["input"]
        system_prompt = source.get("system_prompt")
        if system_prompt != BASE_SYSTEM_PROMPT:
            actual = hashlib.sha256(str(system_prompt).encode()).hexdigest()
            expected = hashlib.sha256(BASE_SYSTEM_PROMPT.encode()).hexdigest()
            raise ValueError(
                f"{path}: system prompt mismatch (actual {actual}, expected {expected})"
            )
        try:
            payload = json.loads(source["user_prompt"])
        except (KeyError, TypeError, json.JSONDecodeError) as error:
            raise ValueError(f"{path}: invalid recorded user prompt") from error
        if not isinstance(payload, dict):
            raise ValueError(f"{path}: user prompt is not an object")
        fields = set(payload)
        if not EXPECTED_USER_FIELDS <= fields or fields - EXPECTED_USER_FIELDS - OPTIONAL_USER_FIELDS:
            raise ValueError(f"{path}: unexpected user fields: {sorted(fields)}")
        if not isinstance(payload.get("briefing"), str) or not payload["briefing"].strip():
            raise ValueError(f"{path}: briefing is empty")
        allowed = payload.get("allowed_actions")
        if not isinstance(allowed, list) or not allowed:
            raise ValueError(f"{path}: allowed_actions is empty")
        decision = pair["output"]
        if not isinstance(decision, dict):
            raise ValueError(f"{path}: decision is not an object")
        validate_decision(decision, allowed)
        prompt = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": canonical_json(payload)},
        ]
        completion = [{"role": "assistant", "content": canonical_json(decision)}]
        prompt_hash = hashlib.sha256(canonical_json(prompt).encode()).hexdigest()
        rows.append({
            "example_id": f"{source_file}::decision::{cycle_id}",
            "source_file": source_file,
            "cycle_id": cycle_id,
            "prompt_sha256": prompt_hash,
            "prompt": prompt,
            "completion": completion,
            "label": decision,
        })
    return rows


def filter_token_lengths(
    rows: list[dict[str, Any]], tokenizer_path: str, max_length: int
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    from transformers import AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(tokenizer_path, local_files_only=True)
    accepted: list[dict[str, Any]] = []
    rejected: list[dict[str, Any]] = []
    for row in rows:
        encoded = tokenizer.apply_chat_template(
            row["prompt"] + row["completion"],
            tokenize=True,
            add_generation_prompt=False,
        )
        token_ids = encoded.input_ids if hasattr(encoded, "input_ids") else encoded
        if len(token_ids) > max_length:
            rejected.append({"example_id": row["example_id"], "tokens": len(token_ids)})
        else:
            row["token_count"] = len(token_ids)
            accepted.append(row)
    return accepted, rejected


def remove_duplicate_prompts(rows: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], int]:
    seen: set[str] = set()
    unique = []
    for row in rows:
        key = row["prompt_sha256"]
        if key in seen:
            continue
        seen.add(key)
        unique.append(row)
    return unique, len(rows) - len(unique)


def balanced_training_rows(
    rows: list[dict[str, Any]], seed: int, max_maintain_fraction: float
) -> list[dict[str, Any]]:
    nonmaintain = [row for row in rows if row["label"]["action"] != "maintain_course"]
    maintain = [row for row in rows if row["label"]["action"] == "maintain_course"]
    if not nonmaintain:
        raise ValueError("training split contains no maneuver decisions")
    cap = int(len(nonmaintain) * max_maintain_fraction / (1.0 - max_maintain_fraction))
    if len(maintain) > cap:
        rng = random.Random(seed)
        rng.shuffle(maintain)
        maintain = maintain[:cap]
    selected = nonmaintain + maintain
    selected.sort(key=lambda row: (row["source_file"], row["cycle_id"]))
    return selected


def training_row(row: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in row.items() if key != "label"}


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    actions = Counter(row["label"]["action"] for row in rows)
    alter_directions = Counter()
    for row in rows:
        if row["label"]["action"] == "alter_course":
            alter_directions[
                "port" if float(row["label"]["degrees"]) < 0.0 else "starboard"
            ] += 1
    tokens = [row["token_count"] for row in rows]
    return {
        "rows": len(rows),
        "missions": len({row["source_file"] for row in rows}),
        "actions": dict(sorted(actions.items())),
        "alter_course_directions": dict(sorted(alter_directions.items())),
        "action_fraction": {
            key: round(value / len(rows), 6) for key, value in sorted(actions.items())
        } if rows else {},
        "token_range": [min(tokens), max(tokens)] if tokens else None,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--minimum-range-m", type=float, default=50.0)
    parser.add_argument("--seed", type=int, default=20261021)
    parser.add_argument("--max-length", type=int, default=4096)
    parser.add_argument("--max-maintain-fraction", type=float, default=0.50)
    parser.add_argument("--tokenizer", default="models/qwen3_8b_oow_colregs_qlora")
    args = parser.parse_args()
    if args.output_dir.exists() and any(args.output_dir.iterdir()):
        parser.error(f"output directory is not empty: {args.output_dir}")
    if not 0.25 <= args.max_maintain_fraction <= 0.60:
        parser.error("--max-maintain-fraction must be between 0.25 and 0.60")

    audits = read_campaign_audits(args.inputs)
    rows: list[dict[str, Any]] = []
    rejected_missions: Counter[str] = Counter()
    teacher_models: Counter[str] = Counter()
    for audit in audits:
        provenance = validate_audit_provenance(audit)
        teacher_models[str(provenance["oow_model"])] += 1
        accepted, reason, _ = audit_quality(audit, args.minimum_range_m)
        if not accepted:
            rejected_missions[reason] += 1
            continue
        episode = episode_rows(audit)
        if not episode:
            rejected_missions["no_usable_decisions"] += 1
            continue
        rows.extend(episode)
    if not rows:
        raise SystemExit("No exact-runtime teacher decisions were found")

    rows, duplicates = remove_duplicate_prompts(rows)
    rows, oversized = filter_token_lengths(rows, args.tokenizer, args.max_length)
    splits = split_by_episode(rows, args.seed)
    balanced = balanced_training_rows(
        splits["train"], args.seed, args.max_maintain_fraction
    )

    args.output_dir.mkdir(parents=True, exist_ok=True)
    write_jsonl(args.output_dir / "paired_all.jsonl", (training_row(row) for row in rows))
    write_jsonl(
        args.output_dir / "train_natural.jsonl",
        (training_row(row) for row in splits["train"]),
    )
    write_jsonl(
        args.output_dir / "train_balanced.jsonl",
        (training_row(row) for row in balanced),
    )
    for split in ("validation", "test"):
        write_jsonl(
            args.output_dir / f"{split}_natural.jsonl",
            (training_row(row) for row in splits[split]),
        )

    mission_sets = {
        name: {row["source_file"] for row in split_rows}
        for name, split_rows in splits.items()
    }
    overlap = {
        "train_validation": mission_sets["train"] & mission_sets["validation"],
        "train_test": mission_sets["train"] & mission_sets["test"],
        "validation_test": mission_sets["validation"] & mission_sets["test"],
    }
    manifest = {
        "ready_for_training": not any(overlap.values()),
        "provenance": "teacher and runtime use byte-identical BASE_SYSTEM_PROMPT and user JSON schema",
        "system_prompt_sha256": hashlib.sha256(BASE_SYSTEM_PROMPT.encode()).hexdigest(),
        "required_user_fields": sorted(EXPECTED_USER_FIELDS),
        "optional_user_fields": sorted(OPTIONAL_USER_FIELDS),
        "forbidden_target_terms": list(FORBIDDEN_TARGET_TERMS),
        "valid_rule_numbers": sorted(VALID_RULES),
        "inputs": [str(path) for path in args.inputs],
        "teacher_models_by_audit": dict(sorted(teacher_models.items())),
        "audits_examined": len(audits),
        "rejected_missions": dict(sorted(rejected_missions.items())),
        "duplicate_prompts_rejected": duplicates,
        "oversized_examples_rejected": len(oversized),
        "max_length": args.max_length,
        "minimum_range_m": args.minimum_range_m,
        "seed": args.seed,
        "max_maintain_fraction": args.max_maintain_fraction,
        "all": summarize(rows),
        "splits": {
            "train_natural": summarize(splits["train"]),
            "train_balanced": summarize(balanced),
            "validation": summarize(splits["validation"]),
            "test": summarize(splits["test"]),
        },
        "mission_overlap": {key: len(value) for key, value in overlap.items()},
    }
    (args.output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
